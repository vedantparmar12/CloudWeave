package report

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/vedantparmar12/cloudweave/internal/analysis"
)

const (
	mdMaxFindings = 50
	mdMaxImpact   = 10
)

var verdictText = map[string]string{
	"block":   "Block apply",
	"review":  "Review required",
	"caution": "Caution",
	"clear":   "No blocking issues",
}

// WriteMarkdown writes a GitHub-flavoured summary sized for a pull request
// comment. Like the other formats it contains addresses and attribute names,
// never attribute values.
func WriteMarkdown(w io.Writer, r *Report) error {
	var b strings.Builder
	fmt.Fprintf(&b, "## CloudWeave preflight: **%s** (%s)\n\n", strings.ToUpper(r.Verdict), verdictText[r.Verdict])

	res, inst := 0, 0
	for _, s := range r.States {
		res += s.Resources
		inst += s.Instances
	}
	fmt.Fprintf(&b, "%d states · %d managed resources · %d instances", len(r.States), res, inst)
	if p := r.Plan; p != nil {
		var parts []string
		for _, a := range []string{"create", "update", "replace", "delete", "forget"} {
			if n := p.Actions[a]; n > 0 {
				parts = append(parts, fmt.Sprintf("%d %s", n, a))
			}
		}
		if len(parts) == 0 {
			parts = []string{"no changes"}
		}
		fmt.Fprintf(&b, "  \n**Plan:** %s · %d drifted", strings.Join(parts, " · "), p.Drift)
		if p.AgeMinutes != nil {
			fmt.Fprintf(&b, " · plan age %d min", *p.AgeMinutes)
		}
	}
	b.WriteString("\n")
	if len(r.ApplyOrder) > 1 {
		order := make([]string, len(r.ApplyOrder))
		for i, s := range r.ApplyOrder {
			order[i] = mdCode(s)
		}
		fmt.Fprintf(&b, "\n**Apply order across states:** %s\n", strings.Join(order, " → "))
	}

	fmt.Fprintf(&b, "\n### Findings (%d)\n\n", len(r.Findings))
	if len(r.Findings) == 0 {
		b.WriteString("No findings.\n")
	} else {
		b.WriteString("| Severity | Rule | Finding | Resources |\n|---|---|---|---|\n")
		for i, f := range r.Findings {
			if i == mdMaxFindings {
				fmt.Fprintf(&b, "\n_%d more findings in the HTML/JSON report._\n", len(r.Findings)-mdMaxFindings)
				break
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", strings.ToUpper(f.Severity.String()), f.Rule, mdText(f.Title), mdNodes(f.Nodes))
		}
		b.WriteString("\n<details><summary>Details and remediation</summary>\n\n")
		for i, f := range r.Findings {
			if i == mdMaxFindings {
				break
			}
			fmt.Fprintf(&b, "- **%s %s**: %s", f.Rule, mdText(f.Title), mdText(f.Detail))
			if f.Remediation != "" {
				fmt.Fprintf(&b, "<br>_Fix:_ %s", mdText(f.Remediation))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n</details>\n")
	}

	if impact := topImpact(r.Nodes); len(impact) > 0 {
		b.WriteString("\n### Largest blast radius\n\n| Change | Action | Impacted | In other states | Why |\n|---|---|---|---|---|\n")
		for _, n := range impact {
			fmt.Fprintf(&b, "| %s | %s | %d | %d | %s |\n", mdCode(n.ID), n.Action+driftSuffix(n), n.Impact, n.CrossImp, mdText(why(n)))
		}
	}

	b.WriteString("\n<sub>" + mdText(r.Disclaimer) + " Generated by CloudWeave " + mdText(r.Version) + ".</sub>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func topImpact(nodes []*analysis.Node) []*analysis.Node {
	var out []*analysis.Node
	for _, n := range nodes {
		if n.Role == analysis.RoleSeed && n.Impact > 0 {
			out = append(out, n)
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].CrossImp != out[j].CrossImp {
			return out[i].CrossImp > out[j].CrossImp
		}
		return out[i].Impact > out[j].Impact
	})
	if len(out) > mdMaxImpact {
		out = out[:mdMaxImpact]
	}
	return out
}

func driftSuffix(n *analysis.Node) string {
	if n.Drift == "" || n.Drift == "no-op" {
		return ""
	}
	if n.Action == "" || n.Action == "no-op" {
		return "drift: " + n.Drift
	}
	return " (drift: " + n.Drift + ")"
}

// why explains a change with attribute names and Terraform's action reason.
func why(n *analysis.Node) string {
	var parts []string
	if len(n.ReplacePaths) > 0 {
		parts = append(parts, "forces replacement: "+strings.Join(n.ReplacePaths, ", "))
	}
	if len(n.ChangedAttrs) > 0 {
		parts = append(parts, "changes "+joinMax(n.ChangedAttrs, 5))
	}
	if len(n.UnknownAttrs) > 0 {
		parts = append(parts, "known after apply: "+joinMax(n.UnknownAttrs, 5))
	}
	if n.SensitiveAttrs > 0 {
		parts = append(parts, fmt.Sprintf("%d sensitive attribute(s) (hidden)", n.SensitiveAttrs))
	}
	for _, r := range n.Reasons {
		parts = append(parts, strings.ReplaceAll(r, "_", " "))
	}
	return strings.Join(parts, "; ")
}

func joinMax(list []string, max int) string {
	if len(list) <= max {
		return strings.Join(list, ", ")
	}
	return strings.Join(list[:max], ", ") + fmt.Sprintf(" +%d", len(list)-max)
}

func mdNodes(ids []string) string {
	if len(ids) == 0 {
		return ""
	}
	s := mdCode(ids[0])
	if len(ids) > 1 {
		s += fmt.Sprintf(" +%d", len(ids)-1)
	}
	return s
}

var mdEscaper = strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;", "\r", " ", "\n", " ")

func mdText(s string) string { return mdEscaper.Replace(s) }

var mdCodeEscaper = strings.NewReplacer("`", "'", "|", `\|`, "\r", " ", "\n", " ")

func mdCode(s string) string { return "`" + mdCodeEscaper.Replace(s) + "`" }
